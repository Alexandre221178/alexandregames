// Helper function to parse power values (e.g., "92k" -> 92000, "1.2m" -> 1200000)
function parsePower(powerStr) {
    if (!powerStr) return 0;
    
    const str = powerStr.toString().toLowerCase().trim();
    
    if (str.includes('m')) {
        return parseFloat(str) * 1000000;
    } else if (str.includes('k')) {
        return parseFloat(str) * 1000;
    }
    
    return parseFloat(str) || 0;
}

// Helper function to format power values
function formatPower(power) {
    if (power >= 1000000) {
        return (power / 1000000).toFixed(1) + 'm';
    } else if (power >= 1000) {
        return (power / 1000).toFixed(0) + 'k';
    }
    return power.toString();
}

// Calculate total power from heroes
function calculateTotalPower(heroes) {
    return heroes.reduce((total, hero) => {
        return total + parsePower(hero.power);
    }, 0);
}

// Get team total power (formatted) - includes main pet for HWDE
function getTeamTotalPower(team) {
    if (team.totalPower) {
        return team.totalPower;
    }
    // Calculate heroes power
    let total = calculateTotalPower(team.heroes);
    
    // Add main pet power if exists (HWDE specific)
    if (team.mainPet && team.mainPet.power) {
        total += parsePower(team.mainPet.power);
    }
    
    return formatPower(total);
}
